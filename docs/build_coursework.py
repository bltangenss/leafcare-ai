ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REP = os.environ.get("REPORTS_DIR", os.path.join(ROOT, "reports"))
SCR = os.environ.get("SCREENS_DIR", os.path.join(ROOT, "docs", "screens"))
OUT = os.environ.get("DOCX_OUT", os.path.join(ROOT, "docs", "Курстық_жұмыс_CNN_өсімдік_аурулары.docx"))


def J(name):
    with open(os.path.join(REP, name), encoding="utf8") as f:
        return json.load(f)


def pct(x, d=2):
    return f"{x * 100:.{d}f}".replace(".", ",")


def num(x, d=1):
    return f"{x:.{d}f}".replace(".", ",")


def thousands(n):
    return f"{n:,}".replace(",", " ")


def short(cls):
    i = get_info(cls)
    return f"{i['plant']} – {i['name'][0].lower() + i['name'][1:]}"


def main():
    split = J("split.json"); classes = split["classes"]
    full = J("full_counts.json")
    C = J("plantcnn_results.json"); M = J("mobilenet_results.json")
    n_plants = len({c.split("___")[0] for c in classes})
    n_healthy = sum("healthy" in c for c in classes)

    d = Doc()
    title_page(d)
    d.toc()
    abbreviations(d)
    intro(d, n_plants)
    chapter1(d)
    chapter2(d, split, full, C, M, n_plants, n_healthy)
    chapter3(d, C, M, classes)
    conclusion(d, C, M, n_plants)
    references(d)
    appendix(d)
    d.save(OUT)
    print("Сақталды:", OUT)


