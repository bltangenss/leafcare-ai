SEVERITY = {0: "Қауіпсіз", 1: "Төмен", 2: "Орташа", 3: "Жоғары"}


def get_info(cls: str) -> dict:
    """Класс атауы бойынша ақпаратты қайтару (атаулардағы шамалы айырмашылыққа төзімді)."""
    key = cls if cls in INFO else next((k for k in INFO if k.lower().replace(" ", "_") == cls.lower().replace(" ", "_")), None)
    if key is None:
        plant, _, dis = cls.partition("___")
        return dict(plant=plant, name=dis.replace("_", " "), pathogen="—", kind="Белгісіз", severity=1,
                    symptoms="", treatment=[], prevention=[], healthy=False, severity_text=SEVERITY[1])
    d = dict(INFO[key])
    d["healthy"] = d["kind"] == H
    if d["healthy"]:
        d["kind"] = "Сау"
        d.setdefault("symptoms", "Жапырақта ауру белгілері анықталған жоқ. Өсімдік сау.")
        d.setdefault("treatment", [])
        d.setdefault("prevention", ["Суару мен қоректендіру режимін сақтау", "Өсімдікті жүйелі түрде тексеріп отыру",
                                    "Ауыспалы егіс пен агротехниканы ұстану"])
    d["severity_text"] = SEVERITY[d["severity"]]
    return d
